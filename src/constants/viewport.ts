import { UseInViewOptions } from 'framer-motion';

type Margin = NonNullable<UseInViewOptions['margin']>;

// Межі спрацювання useInView / whileInView. Задаються у відсотках від
// в'юпорта і лише по вертикалі, а не пікселями з усіх боків.
//
// Піксельний margin віднімається з кожного боку: '-250px' на екрані шириною
// 375px дає root шириною −125px. Chrome обрізає її до нуля й рахує дотик до
// такої лінії перетином (isIntersecting = true при ratio = 0), тож блоки там
// з'являлись — але лише завдяки цьому крайовому випадку і лише з порогом 0.
// На низьких екранах смуга ще й звужувалась до кількох десятків пікселів.
// Відсотки масштабуються з екраном, а горизонталь тут ніколи не була потрібна:
// усі ці блоки на всю ширину.
//
// Відсотки підібрано так, щоб на еталонному 1440×900 межі збігались із
// колишніми пікселями: 4% ≈ 40px, 6% ≈ 50px, 11% ≈ 100px, 22% ≈ 200px,
// 28% ≈ 250px від 900.

// Секція вважається активною, поки перетинає середню смугу екрана: її фон
// увімкнено, а сусідня ще не почалась. Колишні '-250px'.
export const activeZoneMargin: Margin = '-28% 0px -28% 0px';

// Ширша середня смуга — колишні '-100px'.
export const wideActiveZoneMargin: Margin = '-11% 0px -11% 0px';

// Майже весь екран — колишні '-50px'.
export const nearlyFullZoneMargin: Margin = '-6% 0px -6% 0px';

// Трохи ширше за екран: спрацьовує ще до появи — колишні '40px'.
export const beforeEnterMargin: Margin = '4% 0px 4% 0px';
